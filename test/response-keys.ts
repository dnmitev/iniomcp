/** All keys (any depth) of a JSON payload. */
function collectKeys(value: unknown, into: Set<string>): Set<string> {
  if (Array.isArray(value)) {
    for (const v of value) collectKeys(v, into);
  } else if (value !== null && typeof value === 'object') {
    for (const [k, v] of Object.entries(value)) {
      into.add(k);
      collectKeys(v, into);
    }
  }
  return into;
}

/** Sorted keys of `payload` (any depth) that are not in `reviewed`. Removed keys are not reported. */
export function unreviewedKeys(payload: unknown, reviewed: ReadonlySet<string>): string[] {
  return [...collectKeys(payload, new Set())].filter((k) => !reviewed.has(k)).sort();
}
